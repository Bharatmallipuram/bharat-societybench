import requests
from bs4 import BeautifulSoup
import pandas as pd
import datetime
import uuid
import time
import re
import urllib.parse

def scrape_nbt_hindi_articles(query, max_articles=100):
    # Headers for the API call
    api_headers = {
        "accept": "application/json",
        "accept-language": "en-GB,en-US;q=0.9,en;q=0.8",
        "origin": "https://navbharattimes.indiatimes.com",
        "referer": "https://navbharattimes.indiatimes.com/",
        "user-agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/154.0.0.0 Safari/537.36"
    }

    # Standard headers for visiting the actual article pages
    web_headers = {
        "User-Agent": api_headers["user-agent"],
        "Accept-Language": "hi-IN,hi;q=0.9,en-US;q=0.8,en;q=0.7"
    }

    encoded_query = urllib.parse.quote(query)
    articles_meta = []
    seen_urls = set()

    print(f"Searching via API for: {query}...")

    page = 1
    # Step 1: Fetch Search Results via API
    while len(articles_meta) < max_articles:
        api_url = f"https://nbtfeed.indiatimes.com/langapi/search?perpage=20&key={encoded_query}&type=all&curpg={page}"

        try:
            response = requests.get(api_url, headers=api_headers, timeout=10)
            if response.status_code != 200:
                print(f"API Error: Status {response.status_code}")
                break

            json_data = response.json()
            items = json_data.get("items", [])

            if not items:
                break # No more results found

            for item in items:
                # The URL is in 'override', or build it from 'seolocation' and 'id'
                url = item.get("override", "")

                if not url and item.get("seolocation") and item.get("id"):
                    seo = item.get("seolocation").strip('/')
                    url = f"https://navbharattimes.indiatimes.com/{seo}/articleshow/{item.get('id')}.cms"

                if url:
                    if url.startswith('/'):
                        url = "https://navbharattimes.indiatimes.com" + url

                    # Strictly check for articleshow to avoid appending video links
                    if url not in seen_urls and "navbharattimes.indiatimes.com" in url and "/articleshow/" in url:
                        seen_urls.add(url)

                        articles_meta.append({
                            'url': url,
                            'title': item.get("hl", "N/A"),
                            'date': item.get("dl", "N/A"),
                            'id': item.get("id", str(uuid.uuid4()))
                        })

                if len(articles_meta) >= max_articles:
                    break

        except Exception as e:
            print(f"Error fetching API page {page}: {e}")
            break

        page += 1
        time.sleep(1)

    print(f"Found {len(articles_meta)} valid Hindi article links from API. Extracting full text...")

    data = []

    # Step 2: Extract full body text and author from individual article links
    for idx, meta in enumerate(articles_meta, 1):
        url = meta['url']
        print(f"[{idx}/{len(articles_meta)}] Extracting text from: {url}")

        try:
            art_response = requests.get(url, headers=web_headers, timeout=10)
            art_response.encoding = 'utf-8'
            art_soup = BeautifulSoup(art_response.text, 'html.parser')

            # Extract Article Text
            content_node = art_soup.find('article', class_=re.compile(r'story-content', re.I))
            if content_node:
                for extraneous in content_node(["script", "style", "div"]):
                    extraneous.extract()
                text = content_node.get_text(separator=' ', strip=True)
            else:
                paragraphs = art_soup.find_all('p')
                text = " ".join([p.text.strip() for p in paragraphs if len(p.text.strip()) > 30])

            text = text.replace('\n', ' ').strip() if text else "N/A"

            # Extract Author
            author = "N/A"
            bl_div = art_soup.find('div', class_='bl')
            if bl_div and bl_div.find('a'):
                author = bl_div.find('a').text.strip()
            else:
                if "नवभारतटाइम्स" in text or "एनबीटी" in text:
                    author = "नवभारतटाइम्स.कॉम (NBT)"
                elif "भाषा" in text or "PTI" in text:
                    author = "PTI (भाषा)"

            # Combine API data with web-scraped data
            data.append({
                'title': meta['title'],
                'text': text,
                'date': meta['date'],
                'id': meta['id'],
                'url': url,
                'author': author,
                'source_type': 'news',
                'source': 'Navbharat Times',
                'scraped_at': datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                'query': query
            })

            time.sleep(1)

        except Exception as e:
            print(f"Failed to scrape {url}: {e}")

    # Export to CSV
    if data:
        df = pd.DataFrame(data)
        csv_filename = f"nbt_hindi_{query.replace(' ', '_')}_data.csv"
        df.to_csv(csv_filename, index=False, encoding='utf-8-sig')
        print(f"\nSuccess! Saved {len(df)} articles to '{csv_filename}'.")
    else:
        print("\nNo articles could be scraped.")

if __name__ == "__main__":
    scrape_nbt_hindi_articles("Gyanesh kumar CEC", max_articles=100)

